export const DICT: Record<Lang, Dict> = { uz, ru, en };

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: Dict };
const LangCtx = createContext<Ctx>({ lang: "uz", setLang: () => {}, t: uz });

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => {
    try {
      const saved = localStorage.getItem("ewd-lang");
      if (saved === "uz" || saved === "ru" || saved === "en") return saved;
      const nav = navigator.language?.toLowerCase() ?? "";
      if (nav.startsWith("ru")) return "ru";
      if (nav.startsWith("en")) return "en";
    } catch {
      /* ignore */
    }
    return "uz";
  });

  useEffect(() => {
    document.documentElement.lang = lang;
    try {
      localStorage.setItem("ewd-lang", lang);
    } catch {
      /* ignore */
    }
  }, [lang]);
  const value = useMemo(() => ({ lang, setLang, t: DICT[lang] }), [lang]);
  return <LangCtx.Provider value={value}>{children}</LangCtx.Provider>;
}

export const useI18n = () => useContext(LangCtx);
